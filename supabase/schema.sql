-- Core schema for the public protein product comparison dashboard.

CREATE TABLE IF NOT EXISTS public.retailers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    domain text NOT NULL,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    retailer_id bigint NOT NULL REFERENCES public.retailers(id) ON DELETE RESTRICT,
    external_product_id text,
    product_name text NOT NULL,
    brand text,
    category text,
    source_url text NOT NULL,
    image_url text,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT products_retailer_external_id_key
        UNIQUE (retailer_id, external_product_id)
);

CREATE TABLE IF NOT EXISTS public.price_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    snapshot_date date NOT NULL DEFAULT (timezone('UTC', now()))::date,
    price numeric(10, 2) NOT NULL CHECK (price >= 0),
    currency text NOT NULL DEFAULT 'GBP' CHECK (currency = 'GBP'),
    package_quantity numeric(12, 3) CHECK (package_quantity > 0),
    package_unit text CHECK (package_unit IN ('g', 'ml', 'each')),
    price_per_100g numeric(12, 4) GENERATED ALWAYS AS (
        CASE
            WHEN package_unit = 'g' AND package_quantity IS NOT NULL
            THEN price / package_quantity * 100
            ELSE NULL
        END
    ) STORED,
    source_url text,
    scraped_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT price_snapshots_product_date_key UNIQUE (product_id, snapshot_date),
    CONSTRAINT price_snapshots_package_pair_check CHECK (
        (package_quantity IS NULL AND package_unit IS NULL)
        OR (package_quantity IS NOT NULL AND package_unit IS NOT NULL)
    )
);

-- Nutrient values are normalized to 100 g so they can be compared consistently.
CREATE TABLE IF NOT EXISTS public.nutrition_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    snapshot_date date NOT NULL DEFAULT (timezone('UTC', now()))::date,
    energy_kcal numeric(10, 2) CHECK (energy_kcal >= 0),
    protein_g numeric(10, 3) CHECK (protein_g >= 0),
    carbohydrates_g numeric(10, 3) CHECK (carbohydrates_g >= 0),
    sugars_g numeric(10, 3) CHECK (sugars_g >= 0),
    fat_g numeric(10, 3) CHECK (fat_g >= 0),
    saturates_g numeric(10, 3) CHECK (saturates_g >= 0),
    fibre_g numeric(10, 3) CHECK (fibre_g >= 0),
    salt_g numeric(10, 3) CHECK (salt_g >= 0),
    serving_size_g numeric(10, 3) CHECK (serving_size_g > 0),
    source text,
    scraped_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT nutrition_snapshots_product_date_key UNIQUE (product_id, snapshot_date)
);

CREATE TABLE IF NOT EXISTS public.scrape_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    retailer_id bigint REFERENCES public.retailers(id) ON DELETE SET NULL,
    status text NOT NULL DEFAULT 'running'
        CHECK (status IN ('running', 'succeeded', 'partial', 'failed')),
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    products_seen integer NOT NULL DEFAULT 0 CHECK (products_seen >= 0),
    products_updated integer NOT NULL DEFAULT 0 CHECK (products_updated >= 0),
    error_message text,
    CONSTRAINT scrape_runs_finished_after_started_check
        CHECK (finished_at IS NULL OR finished_at >= started_at)
);

CREATE INDEX IF NOT EXISTS products_retailer_id_idx
    ON public.products (retailer_id);
CREATE INDEX IF NOT EXISTS products_category_idx
    ON public.products (category);
CREATE INDEX IF NOT EXISTS products_name_idx
    ON public.products (product_name);
CREATE INDEX IF NOT EXISTS price_snapshots_product_date_desc_idx
    ON public.price_snapshots (product_id, snapshot_date DESC);
CREATE INDEX IF NOT EXISTS nutrition_snapshots_product_date_desc_idx
    ON public.nutrition_snapshots (product_id, snapshot_date DESC);
CREATE INDEX IF NOT EXISTS scrape_runs_retailer_started_desc_idx
    ON public.scrape_runs (retailer_id, started_at DESC);

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS products_set_updated_at ON public.products;
CREATE TRIGGER products_set_updated_at
    BEFORE UPDATE ON public.products
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE public.retailers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.price_snapshots ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.nutrition_snapshots ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.scrape_runs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can read active retailers" ON public.retailers;
CREATE POLICY "Public can read active retailers"
    ON public.retailers FOR SELECT
    TO anon, authenticated
    USING (active);

DROP POLICY IF EXISTS "Public can read active products" ON public.products;
CREATE POLICY "Public can read active products"
    ON public.products FOR SELECT
    TO anon, authenticated
    USING (
        active
        AND EXISTS (
            SELECT 1
            FROM public.retailers
            WHERE retailers.id = products.retailer_id
              AND retailers.active
        )
    );

DROP POLICY IF EXISTS "Public can read price history" ON public.price_snapshots;
CREATE POLICY "Public can read price history"
    ON public.price_snapshots FOR SELECT
    TO anon, authenticated
    USING (
        EXISTS (
            SELECT 1 FROM public.products
            WHERE products.id = price_snapshots.product_id
        )
    );

DROP POLICY IF EXISTS "Public can read nutrition history" ON public.nutrition_snapshots;
CREATE POLICY "Public can read nutrition history"
    ON public.nutrition_snapshots FOR SELECT
    TO anon, authenticated
    USING (
        EXISTS (
            SELECT 1 FROM public.products
            WHERE products.id = nutrition_snapshots.product_id
        )
    );

GRANT SELECT ON public.retailers, public.products,
    public.price_snapshots, public.nutrition_snapshots
    TO anon, authenticated;
GRANT ALL ON public.retailers, public.products, public.price_snapshots,
    public.nutrition_snapshots, public.scrape_runs
    TO service_role;
