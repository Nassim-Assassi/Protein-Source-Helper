-- Core PostgreSQL schema for the protein product comparison dashboard
DROP TABLE IF EXISTS public.retailer CASCADE;
DROP TABLE IF EXISTS public.retailer_category CASCADE;
DROP TABLE IF EXISTS public.brand CASCADE;
DROP TABLE IF EXISTS public.canonical_product CASCADE;
DROP TABLE IF EXISTS public.retailer_listing CASCADE;
DROP TABLE IF EXISTS public.scrape_batch CASCADE;
DROP TABLE IF EXISTS public.scrape_run CASCADE;
DROP TABLE IF EXISTS public.snapshot CASCADE;
DROP MATERIALIZED VIEW IF EXISTS public.current_data_mat CASCADE;

CREATE TABLE IF NOT EXISTS public.retailer (
    retailer_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    retailer_name text NOT NULL UNIQUE,
    retailer_url text NOT NULL UNIQUE,
    retailer_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS public.retailer_category (
    retailer_category_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    retailer_id int NOT NULL REFERENCES public.retailer (
        retailer_id
    ) ON DELETE RESTRICT,
    retailer_category_name text NOT NULL,
    CONSTRAINT retailer_category_retailer_name_key UNIQUE (
        retailer_id, retailer_category_name
    ),
    CONSTRAINT retailer_category_id_retailer_id_key UNIQUE (
        retailer_category_id, retailer_id
    )
);

CREATE TABLE IF NOT EXISTS public.brand (
    brand_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_name text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS public.canonical_product (
    canonical_product_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_product_name text NOT NULL UNIQUE,
    barcode_gtin text UNIQUE,
    brand_id int REFERENCES public.brand (brand_id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS public.retailer_listing (
    retailer_listing_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_product_id int NOT NULL REFERENCES public.canonical_product (
        canonical_product_id
    ) ON DELETE RESTRICT,
    retailer_category_id int,
    retailer_id int NOT NULL REFERENCES public.retailer (
        retailer_id
    ) ON DELETE RESTRICT,
    retailer_listing_external_id text,
    retailer_listing_name text NOT NULL,
    retailer_listing_source_url text NOT NULL,
    retailer_listing_image_url text,
    retailer_listing_active boolean NOT NULL DEFAULT true,
    CONSTRAINT retailer_listing_id_retailer_id_key UNIQUE (
        retailer_listing_id, retailer_id
    ),
    CONSTRAINT retailer_listing_retailer_category_fkey
    FOREIGN KEY (retailer_category_id, retailer_id)
    REFERENCES public.retailer_category (
        retailer_category_id, retailer_id
    ) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS retailer_listing_retailer_external_id_key
ON public.retailer_listing (retailer_id, retailer_listing_external_id)
WHERE retailer_listing_external_id IS NOT null;

CREATE UNIQUE INDEX IF NOT EXISTS retailer_listing_retailer_source_url_key
ON public.retailer_listing (retailer_id, retailer_listing_source_url)
WHERE retailer_listing_external_id IS null;

CREATE TABLE IF NOT EXISTS public.scrape_batch (
    scrape_batch_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scrape_batch_status text NOT NULL
    CHECK (
        scrape_batch_status IN ('running', 'succeeded', 'partial', 'failed')
    ),
    scrape_batch_started_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    scrape_batch_finished_at timestamptz,
    scrape_batch_error_message text,
    CONSTRAINT scrape_batch_finished_after_started_check
    CHECK (
        scrape_batch_finished_at IS null
        OR scrape_batch_finished_at >= scrape_batch_started_at
    ),
    CONSTRAINT scrape_batch_status_finished_at_check
    CHECK (
        (scrape_batch_status = 'running' AND scrape_batch_finished_at IS null)
        OR (
            scrape_batch_status <> 'running'
            AND scrape_batch_finished_at IS NOT null
        )
    )
);

CREATE TABLE IF NOT EXISTS public.scrape_run (
    scrape_run_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scrape_batch_id int NOT NULL
    REFERENCES public.scrape_batch (scrape_batch_id) ON DELETE RESTRICT,
    retailer_id int NOT NULL
    REFERENCES public.retailer (retailer_id) ON DELETE RESTRICT,
    scrape_run_status text NOT NULL
    CHECK (scrape_run_status IN ('running', 'succeeded', 'failed')),
    scrape_run_started_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    scrape_run_finished_at timestamptz,
    scrape_run_error_message text,
    CONSTRAINT scrape_run_finished_after_started_check
    CHECK (
        scrape_run_finished_at IS null
        OR scrape_run_finished_at >= scrape_run_started_at
    ),
    CONSTRAINT scrape_run_status_finished_at_check
    CHECK (
        (scrape_run_status = 'running' AND scrape_run_finished_at IS null)
        OR (
            scrape_run_status <> 'running'
            AND scrape_run_finished_at IS NOT null
        )
    ),
    CONSTRAINT scrape_run_id_retailer_id_key UNIQUE (
        scrape_run_id, retailer_id
    ),
    CONSTRAINT scrape_run_batch_retailer_key UNIQUE (
        scrape_batch_id, retailer_id
    )
);

CREATE TABLE IF NOT EXISTS public.snapshot (
    snapshot_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    retailer_id int NOT NULL,
    retailer_listing_id int NOT NULL,
    scrape_run_id int NOT NULL,
    snapshot_price numeric(10, 2) NOT NULL CHECK (snapshot_price >= 0),
    snapshot_package_quantity numeric(12, 3) NOT NULL CHECK (
        snapshot_package_quantity > 0
    ),
    snapshot_package_unit text NOT NULL CHECK (
        snapshot_package_unit IN ('g', 'ml', 'each')
    ),
    snapshot_energy_kcal numeric(10, 2) NOT NULL CHECK (
        snapshot_energy_kcal >= 0
    ),
    snapshot_protein_g numeric(10, 3) NOT NULL CHECK (snapshot_protein_g >= 0),
    snapshot_carbohydrates_g numeric(10, 3) CHECK (
        snapshot_carbohydrates_g >= 0
    ),
    snapshot_sugars_g numeric(10, 3) CHECK (snapshot_sugars_g >= 0),
    snapshot_fat_g numeric(10, 3) CHECK (snapshot_fat_g >= 0),
    snapshot_saturates_g numeric(10, 3) CHECK (snapshot_saturates_g >= 0),
    snapshot_fibre_g numeric(10, 3) CHECK (snapshot_fibre_g >= 0),
    snapshot_salt_g numeric(10, 3) CHECK (snapshot_salt_g >= 0),
    snapshot_nutrition_basis text NOT NULL
    CHECK (snapshot_nutrition_basis IN ('per_100g', 'per_100ml', 'per_item')),
    snapshot_nutrition_source text,
    snapshot_out_of_stock boolean NOT NULL DEFAULT false,
    CONSTRAINT snapshot_retailer_listing_fkey
    FOREIGN KEY (retailer_listing_id, retailer_id)
    REFERENCES public.retailer_listing (
        retailer_listing_id, retailer_id
    ) ON DELETE RESTRICT,
    CONSTRAINT snapshot_scrape_run_retailer_fkey
    FOREIGN KEY (scrape_run_id, retailer_id)
    REFERENCES public.scrape_run (
        scrape_run_id, retailer_id
    ) ON DELETE RESTRICT,
    CONSTRAINT snapshot_retailer_listing_scrape_run_key
    UNIQUE (retailer_listing_id, scrape_run_id),
    CONSTRAINT snapshot_retailer_listing_package_unit_nutrition_basis_check
    CHECK (
        (snapshot_nutrition_basis = 'per_100g' AND snapshot_package_unit = 'g')
        OR (
            snapshot_nutrition_basis = 'per_100ml'
            AND snapshot_package_unit = 'ml'
        )
        OR (
            snapshot_nutrition_basis = 'per_item'
            AND snapshot_package_unit = 'each'
        )
    )
);

