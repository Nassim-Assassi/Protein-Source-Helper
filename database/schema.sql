-- Core PostgreSQL schema for the protein product comparison dashboard

CREATE TABLE IF NOT EXISTS public.retailer (
    retailer_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    retailer_name text NOT NULL UNIQUE,
    retailer_url text NOT NULL UNIQUE,
    retailer_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS public.brand (
    brand_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_name text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS public.category (
    category_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS public.product (
    product_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    retailer_id int NOT NULL
        REFERENCES public.retailer(retailer_id) ON DELETE RESTRICT,
    brand_id int REFERENCES public.brand(brand_id) ON DELETE SET NULL,
    category_id int REFERENCES public.category(category_id) ON DELETE SET NULL,
    barcode_gtin text,
    product_external_id text,
    product_name text NOT NULL,
    product_source_url text NOT NULL,
    product_image_url text,
    product_active boolean NOT NULL DEFAULT true,
    CONSTRAINT product_id_retailer_id_key UNIQUE (product_id, retailer_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS product_retailer_external_id_key
    ON public.product (retailer_id, product_external_id)
    WHERE product_external_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS product_retailer_source_url_without_external_id_key
    ON public.product (retailer_id, product_source_url)
    WHERE product_external_id IS NULL;

CREATE INDEX IF NOT EXISTS product_barcode_gtin_idx
    ON public.product (barcode_gtin)
    WHERE barcode_gtin IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.scrape_batch (
    scrape_batch_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scrape_batch_started_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    scrape_batch_finished_at timestamptz,
    scrape_batch_error_message text,
    CONSTRAINT scrape_batch_finished_after_started_check
        CHECK (
            scrape_batch_finished_at IS NULL
            OR scrape_batch_finished_at >= scrape_batch_started_at
        )
);

CREATE TABLE IF NOT EXISTS public.scrape_run (
    scrape_run_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scrape_batch_id int NOT NULL
        REFERENCES public.scrape_batch(scrape_batch_id) ON DELETE RESTRICT,
    retailer_id int NOT NULL
        REFERENCES public.retailer(retailer_id) ON DELETE RESTRICT,
    scrape_run_status text NOT NULL
        CHECK (scrape_run_status IN ('running', 'succeeded', 'failed')),
    scrape_run_started_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    scrape_run_finished_at timestamptz,
    scrape_run_error_message text,
    CONSTRAINT scrape_run_finished_after_started_check
        CHECK (
            scrape_run_finished_at IS NULL
            OR scrape_run_finished_at >= scrape_run_started_at
        ),
    CONSTRAINT scrape_run_status_finished_at_check
        CHECK (
            (scrape_run_status = 'running' AND scrape_run_finished_at IS NULL)
            OR (scrape_run_status <> 'running' AND scrape_run_finished_at IS NOT NULL)
        ),
    CONSTRAINT scrape_run_id_retailer_id_key UNIQUE (scrape_run_id, retailer_id),
    CONSTRAINT scrape_run_batch_retailer_key UNIQUE (scrape_batch_id, retailer_id)
);

CREATE TABLE IF NOT EXISTS public.snapshot (
    snapshot_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    retailer_id int NOT NULL,
    product_id int NOT NULL,
    scrape_run_id int NOT NULL,
    snapshot_price numeric(10, 2) NOT NULL CHECK (snapshot_price >= 0),
    snapshot_package_quantity numeric(12, 3) CHECK (snapshot_package_quantity > 0),
    snapshot_package_unit text CHECK (snapshot_package_unit IN ('g', 'ml', 'each')),
    snapshot_energy_kcal numeric(10, 2) NOT NULL CHECK (snapshot_energy_kcal >= 0),
    snapshot_protein_g numeric(10, 3) NOT NULL CHECK (snapshot_protein_g >= 0),
    snapshot_carbohydrates_g numeric(10, 3) CHECK (snapshot_carbohydrates_g >= 0),
    snapshot_sugars_g numeric(10, 3) CHECK (snapshot_sugars_g >= 0),
    snapshot_fat_g numeric(10, 3) CHECK (snapshot_fat_g >= 0),
    snapshot_saturates_g numeric(10, 3) CHECK (snapshot_saturates_g >= 0),
    snapshot_fibre_g numeric(10, 3) CHECK (snapshot_fibre_g >= 0),
    snapshot_salt_g numeric(10, 3) CHECK (snapshot_salt_g >= 0),
    snapshot_nutrition_basis text NOT NULL
        CHECK (snapshot_nutrition_basis IN ('per_100g', 'per_100ml')),
    snapshot_nutrition_source text,
    CONSTRAINT snapshot_product_retailer_fkey
        FOREIGN KEY (product_id, retailer_id)
        REFERENCES public.product (product_id, retailer_id) ON DELETE RESTRICT,
    CONSTRAINT snapshot_scrape_run_retailer_fkey
        FOREIGN KEY (scrape_run_id, retailer_id)
        REFERENCES public.scrape_run (scrape_run_id, retailer_id) ON DELETE RESTRICT,
    CONSTRAINT snapshot_package_pair_check CHECK (
        (snapshot_package_quantity IS NULL AND snapshot_package_unit IS NULL)
        OR (snapshot_package_quantity IS NOT NULL AND snapshot_package_unit IS NOT NULL)
    ),
    CONSTRAINT snapshot_product_scrape_run_key
        UNIQUE (product_id, scrape_run_id)
);

-- Performance Indexes
CREATE INDEX IF NOT EXISTS product_retailer_id_idx ON public.product (retailer_id);
CREATE INDEX IF NOT EXISTS product_brand_id_idx ON public.product (brand_id);
CREATE INDEX IF NOT EXISTS product_category_id_idx ON public.product (category_id);
CREATE INDEX IF NOT EXISTS product_name_idx ON public.product (product_name);

CREATE INDEX IF NOT EXISTS scrape_run_batch_id_idx ON public.scrape_run (scrape_batch_id);
CREATE INDEX IF NOT EXISTS scrape_run_successful_finished_idx
    ON public.scrape_run (retailer_id, scrape_run_finished_at DESC, scrape_run_id DESC)
    WHERE scrape_run_status = 'succeeded';

CREATE INDEX IF NOT EXISTS snapshot_scrape_run_id_idx ON public.snapshot (scrape_run_id);

DROP VIEW IF EXISTS public.current_data;

CREATE OR REPLACE VIEW public.current_data AS
WITH latest_successful_run AS (
    SELECT DISTINCT ON (retailer_id)
        scrape_run_id,
        retailer_id,
        scrape_run_started_at,
        scrape_run_finished_at
    FROM public.scrape_run
    WHERE scrape_run_status = 'succeeded'
      AND scrape_run_finished_at >= statement_timestamp() - interval '24 hours'
    ORDER BY retailer_id, scrape_run_finished_at DESC, scrape_run_id DESC
)
SELECT
    -- Product Details
    p.product_id,
    p.product_name,
    p.product_external_id,
    p.barcode_gtin,
    p.product_source_url,
    p.product_image_url,
    p.product_active,
    -- Retailer Details
    r.retailer_id,
    r.retailer_name,
    r.retailer_url,
    
    -- Brand & Category (Nullable)
    b.brand_id,
    b.brand_name,
    c.category_id,
    c.category_name,
    
    -- Latest Successful Snapshot Data
    s.snapshot_id,
    s.snapshot_price,
    s.snapshot_package_quantity,
    s.snapshot_package_unit,
    s.snapshot_energy_kcal,
    s.snapshot_protein_g,
    s.snapshot_carbohydrates_g,
    s.snapshot_sugars_g,
    s.snapshot_fat_g,
    s.snapshot_saturates_g,
    s.snapshot_fibre_g,
    s.snapshot_salt_g,
    s.snapshot_nutrition_basis,
    s.snapshot_nutrition_source,
    
    -- Associated Run Details
    latest.scrape_run_id,
    latest.scrape_run_started_at,
    latest.scrape_run_finished_at
FROM latest_successful_run latest
JOIN public.snapshot s
    ON s.scrape_run_id = latest.scrape_run_id
   AND s.retailer_id = latest.retailer_id
JOIN public.product p
    ON p.product_id = s.product_id
   AND p.retailer_id = s.retailer_id
JOIN public.retailer r 
    ON r.retailer_id = p.retailer_id
LEFT JOIN public.brand b 
    ON b.brand_id = p.brand_id
LEFT JOIN public.category c 
    ON c.category_id = p.category_id
WHERE p.product_active = true 
  AND r.retailer_active = true;